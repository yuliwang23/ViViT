#ifndef VIVIT_CONFIG_H
#define VIVIT_CONFIG_H

// Set to 0 for the original ViViT-sized synthesis.
#ifndef VIVIT_SMALL_CONFIG
#define VIVIT_SMALL_CONFIG 1
#endif

#if VIVIT_SMALL_CONFIG

#define VIVIT_SEQ_LEN 4
#define VIVIT_EMBED_DIM 64
#define VIVIT_NUM_HEADS 2
#define VIVIT_FRAME 2
#define VIVIT_MLP_DIM 256
#define VIVIT_NUM_ENCODER_BLOCKS 1
#define VIVIT_TEMP_LEN 3

#define VIVIT_LINEAR_TILE_SIZE 32
#define VIVIT_LINEAR_SEQ_TILE_SIZE 32
#define VIVIT_ATTENTION_TILE_SIZE 8
#define VIVIT_OUT_TILE 32
#define VIVIT_DOT_UNROLL 8
#define VIVIT_DSP_PER_CYCLE 8

#else

#define VIVIT_SEQ_LEN (14 * 14 + 1)
#define VIVIT_EMBED_DIM 768
#define VIVIT_NUM_HEADS 12
#define VIVIT_FRAME 16
#define VIVIT_MLP_DIM 3072
#define VIVIT_NUM_ENCODER_BLOCKS 12
#define VIVIT_TEMP_LEN 17

#define VIVIT_LINEAR_TILE_SIZE 64
#define VIVIT_LINEAR_SEQ_TILE_SIZE 64
#define VIVIT_ATTENTION_TILE_SIZE 16
#define VIVIT_OUT_TILE 64
#define VIVIT_DOT_UNROLL 16
#define VIVIT_DSP_PER_CYCLE 16

#endif

#define VIVIT_HEAD_DIM (VIVIT_EMBED_DIM / VIVIT_NUM_HEADS)
#if VIVIT_SMALL_CONFIG
#define VIVIT_ATTENTION_SCALE 0.176776695f
#else
#define VIVIT_ATTENTION_SCALE 0.125f
#endif
#define VIVIT_EMBED_DIM_PACKAGE (VIVIT_EMBED_DIM / 8)
#define VIVIT_MLP_DIM_PACKAGE (VIVIT_MLP_DIM / 8)
#define VIVIT_LAYER_NORM_ITERATIONS (VIVIT_EMBED_DIM / 16)
#define VIVIT_ATTENTION_NUM_TILES ((VIVIT_SEQ_LEN + VIVIT_ATTENTION_TILE_SIZE - 1) / VIVIT_ATTENTION_TILE_SIZE)
#define VIVIT_LINEAR_TILE_SQL_TIME (VIVIT_SEQ_LEN / VIVIT_LINEAR_SEQ_TILE_SIZE)
#define VIVIT_LINEAR_TILE_SQL_REMAIN (VIVIT_SEQ_LEN % VIVIT_LINEAR_SEQ_TILE_SIZE)
#define VIVIT_EMBED_FP_PACKED_DEPTH (VIVIT_SEQ_LEN * VIVIT_EMBED_DIM / 8)
#define VIVIT_EMBED_INT8_PACKED_DEPTH (VIVIT_SEQ_LEN * VIVIT_EMBED_DIM / 32)
#define VIVIT_QKV_FP_PACKED_DEPTH (VIVIT_NUM_HEADS * VIVIT_SEQ_LEN * VIVIT_HEAD_DIM / 8)
#define VIVIT_EMBED_VEC_PACKED_DEPTH (VIVIT_EMBED_DIM / 8)
#define VIVIT_EMBED_WEIGHT_INT8_PACKED_DEPTH (VIVIT_EMBED_DIM * VIVIT_EMBED_DIM / 32)
#define VIVIT_MLP_WEIGHT_INT8_PACKED_DEPTH (VIVIT_MLP_DIM * VIVIT_EMBED_DIM / 32)

static_assert(VIVIT_EMBED_DIM % VIVIT_NUM_HEADS == 0, "embedding dimension must split evenly across heads");
static_assert(VIVIT_HEAD_DIM % 8 == 0, "head dimension must align with 256-bit float packing");
static_assert(VIVIT_EMBED_DIM % 8 == 0, "embedding dimension must align with 256-bit packing");
static_assert(VIVIT_EMBED_DIM % 16 == 0, "layernorm expects 16-wide reduction chunks");
static_assert(VIVIT_MLP_DIM == 4 * VIVIT_EMBED_DIM, "MLP expansion must be 4x embedding dimension");

#endif
